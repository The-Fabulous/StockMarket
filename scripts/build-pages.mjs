import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const source = readFileSync(new URL('public/index.html', root), 'utf8').replace(/\r\n/g, '\n');
const html = '<!-- Generated by npm run build:pages. Edit public/index.html instead. -->\n' + source
  .replace('<html lang="ru">', '<html lang="ru" data-mode="demo">')
  .replace('href="./favicon.svg"', 'href="./public/favicon.svg"')
  .replace('href="./styles.css"', 'href="./public/styles.css"')
  .replace('src="./app.js"', 'src="./public/app.js"');
if (process.argv.includes('--check')) {
  if (readFileSync(new URL('index.html', root), 'utf8').replace(/\r\n/g, '\n') !== html) throw new Error('Run npm run build:pages to update the GitHub Pages entrypoint.');
} else {
  writeFileSync(new URL('index.html', root), html);
  writeFileSync(new URL('.nojekyll', root), '');
  console.log(`GitHub Pages entrypoint: ${fileURLToPath(new URL('index.html', root))}`);
}
